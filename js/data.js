/* ---------- 由骨架展开为章节数组 ---------- */
const CHAPTERS = [];
(function buildSkeleton() {
  for (const stage in PEP_SKELETON) {
    const grades = PEP_SKELETON[stage];
    for (const grade in grades) {
      const vols = grades[grade];
      for (const vol in vols) {
        vols[vol].forEach((title, i) => {
          const id = STAGE_CODE[stage] + GRADE_CODE[grade] + VOL_CODE[vol] + "c" + (i + 1);
          const ch = {
            id, stage, grade, vol, no: i + 1, title,
            summary: "", methods: [], knowledge: [], questions: [], built: false
          };
          if (BUILT[id]) {
            Object.assign(ch, BUILT[id]);
            ch.built = true;
          }
          CHAPTERS.push(ch);
        });
      }
    }
  }
})();

/* ---------- 合并外部知识梳理卡（js/knowledge.js） ---------- */
/* knowledge.js 在 data.js 之前加载，定义 window.PEP_KNOWLEDGE：{ 章id: {summary, knowledge} } */
(function mergeKnowledge() {
  const PK = window.PEP_KNOWLEDGE;
  if (!PK) return;
  CHAPTERS.forEach(ch => {
    const k = PK[ch.id];
    if (!k) return;
    if (k.summary) ch.summary = k.summary;
    if (k.knowledge && k.knowledge.length) {
      ch.knowledge = k.knowledge;
      ch.built = true; // 已有知识卡 + qgen 可供给练习，放开练习与「标记掌握」
    }
  });
})();

/* ---------- 学段默认学习方法（骨架章也按学段展示对应学法） ---------- */
function stageDefaultMethods(stage) {
  if (stage === "小学") return ["preview", "closeread", "mistake", "spaced"];
  if (stage === "初中") return ["preview", "closeread", "summarize", "compare", "mistake", "spaced"];
  return ["closeread", "summarize", "compare", "solve", "feynman", "mistake", "spaced"];
}
function chapterMethods(ch) {
  return (ch.methods && ch.methods.length) ? ch.methods : stageDefaultMethods(ch.stage);
}

/* 章节顺序（用于年级内顺序解锁的单一事实来源） */
const CHAPTER_ORDER = {};
CHAPTERS.forEach((c, i) => { CHAPTER_ORDER[c.id] = i; });

/* 小组键：同 学段+年级/册 视为一组，组内顺序解锁 */
function groupKey(ch) { return ch.stage + "|" + ch.grade; }

/* 小工具：随机整数（可排除 0） */
function ri(min, max, exclude) {
  let v;
  do { v = Math.floor(Math.random() * (max - min + 1)) + min; } while (v === exclude);
  return v;
}
